import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const researcherId = "hiroaki-murakami";
const outputPath = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/data/publications.generated.ts",
);
const endpoint = `https://api.researchmap.jp/${researcherId}/published_papers?limit=1000`;

const categoryFor = (type) => {
  if (type === "scientific_journal") return "journal";
  if (type === "international_conference_proceedings") return "conference";
  return null;
};

const valueFor = (localized = {}, preferredLanguage = "en") => {
  if (localized[preferredLanguage]) return localized[preferredLanguage];
  return localized.en ?? localized.ja ?? Object.values(localized).find(Boolean) ?? "";
};

const containsJapanese = (value) => /[\u3040-\u30ff\u3400-\u9fff]/.test(value);

const chooseTitle = (item) => {
  const ja = item.paper_title?.ja;
  const en = item.paper_title?.en;
  if (ja && containsJapanese(ja)) return { value: ja, language: "ja" };
  return { value: en ?? ja ?? "", language: en ? "en" : "ja" };
};

const authorNames = (item, language) => {
  const authors = item.authors?.[language] ?? item.authors?.en ?? item.authors?.ja ?? [];
  return authors.map((author) => author.name).filter(Boolean);
};

const yearFor = (publicationDate) => {
  const match = String(publicationDate ?? "").match(/^\d{4}/);
  return match ? Number(match[0]) : new Date().getFullYear();
};

const doiFor = (item) => {
  const doi = item.identifiers?.doi?.[0];
  if (doi) return `https://doi.org/${doi}`;
  const doiLink = item.see_also?.find((link) => link.label?.toLowerCase() === "doi")?.["@id"];
  return doiLink;
};

const toPublication = (item) => {
  const category = categoryFor(item.published_paper_type);
  if (!category || item.referee === false) return null;

  const title = chooseTitle(item);
  if (!title.value) return null;

  const doi = doiFor(item);
  return {
    sourceId: item["rm:id"],
    title: title.value,
    authors: authorNames(item, title.language),
    year: yearFor(item.publication_date),
    category,
    venue: valueFor(item.publication_name, title.language),
    publicationType: category === "journal" ? "Journal Article" : "Full Paper",
    ...(doi ? { links: { doi } } : {}),
  };
};

const response = await fetch(endpoint);
if (!response.ok) {
  throw new Error(`researchmap API request failed: ${response.status} ${response.statusText}`);
}

const data = await response.json();
const publications = data.items
  .map(toPublication)
  .filter(Boolean)
  .sort((a, b) => b.year - a.year || Number(b.sourceId) - Number(a.sourceId));

const source = `// This file is generated by scripts/update-publications.mjs.
// Do not edit this file directly; edit publication-overrides.ts for site-specific metadata.

import type { Publication } from "./publications";

export const generatedPublications: Publication[] = ${JSON.stringify(publications, null, 2)};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);

console.log(`Wrote ${publications.length} publications to ${outputPath}`);
